#!/usr/bin/env python3
"""Embed the library's own animations (animations/*.xaan, FORMATS.md section 4.8) in the library: prints a C header with
each file's bytes as an array, for src/avatar_walk_clip.c. Python 3 standard library only, as xsdk's host tools.

  python3 gen_clips.py <animations folder> > avatar_clips.h

An array is named after its file: walk_male.xaan becomes clip_walk_male[] and clip_walk_male_size.
"""

import re
import sys
from pathlib import Path


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__.strip().splitlines()[2])
    folder = Path(sys.argv[1])
    files = sorted(folder.glob("*.xaan"))
    if not files:
        sys.exit(f"{folder}: no .xaan files")
    out = ["// Generated by tools/gen_clips.py from animations/*.xaan: don't edit.", "#pragma once", "#include <stdint.h>", ""]
    for path in files:
        name = "clip_" + re.sub(r"[^0-9A-Za-z]", "_", path.stem)
        data = path.read_bytes()
        out.append(f"static const uint8_t {name}[{len(data)}] __attribute__((aligned(4))) = {{")
        for at in range(0, len(data), 24):
            out.append("\t" + ", ".join(f"0x{b:02x}" for b in data[at:at + 24]) + ",")
        out.append("};")
        out.append(f"static const uint32_t {name}_size = {len(data)};")
        out.append("")
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
